import React, { useState } from 'react';
import { PenTool, Loader2, FileText, Copy, RefreshCw, Eye, Sparkles, CheckCircle2, AlertTriangle, Check, Link as LinkIcon, Code2, Download } from 'lucide-react';
import { jsPDF } from 'jspdf';
import { generateBlogStream, analyzeContent } from '../services/geminiService';
import { ContentAnalysis } from '../types';

const ContentGenerator: React.FC = () => {
  const [topic, setTopic] = useState('');
  const [tone, setTone] = useState('Informative');
  const [content, setContent] = useState('');
  const [isGenerating, setIsGenerating] = useState(false);
  
  // SEO Analysis State
  const [activeTab, setActiveTab] = useState<'preview' | 'seo'>('preview');
  const [analysis, setAnalysis] = useState<ContentAnalysis | null>(null);
  const [isAnalyzing, setIsAnalyzing] = useState(false);
  const [checkedItems, setCheckedItems] = useState<Set<number>>(new Set());
  const [isCopied, setIsCopied] = useState(false);

  // Calculate word count
  const wordCount = content 
    ? content.replace(/<[^>]+>/g, ' ').trim().split(/\s+/).filter(w => w.length > 0).length 
    : 0;

  const handleGenerate = async () => {
    if (!topic.trim()) return;
    setIsGenerating(true);
    setContent('');
    setAnalysis(null); // Reset analysis when new content is generated
    setCheckedItems(new Set());
    setActiveTab('preview');
    
    try {
      const stream = await generateBlogStream(topic, tone);
      for await (const chunk of stream) {
        setContent(prev => prev + chunk.text);
      }
    } catch (error) {
      console.error("Failed to generate", error);
    } finally {
      setIsGenerating(false);
    }
  };

  const handleAnalyze = async () => {
    if (!content || !topic) return;
    setIsAnalyzing(true);
    try {
      const result = await analyzeContent(content, topic);
      setAnalysis(result);
      setCheckedItems(new Set());
    } catch (error) {
      console.error("Analysis failed", error);
    } finally {
      setIsAnalyzing(false);
    }
  };

  const toggleCheck = (index: number) => {
    setCheckedItems(prev => {
      const next = new Set(prev);
      if (next.has(index)) next.delete(index);
      else next.add(index);
      return next;
    });
  };

  const handleCopyAnalysis = () => {
    if (!analysis) return;
    
    const report = [
        `SEO ANALYSIS REPORT`,
        `Topic: ${topic || 'Untitled Content'}`,
        `Date: ${new Date().toLocaleDateString()}`,
        `Generated by OrganicIQ`,
        `================================================`,
        
        `\n1. READABILITY`,
        `Score: ${analysis.readability.level}`,
        `Suggestions:`,
        ...analysis.readability.suggestions.map(s => `• ${s}`),
        
        `\n2. KEYWORD STRATEGY`,
        ...analysis.keywordAnalysis.map(k => `• ${k.keyword}: ${k.count} uses (${k.status})`),
        
        `\n3. META DESCRIPTIONS`,
        ...analysis.metaDescriptions.map((d, i) => `${i+1}. ${d}`),
        
        `\n4. INTERNAL LINKING OPPORTUNITIES`,
        ...analysis.internalLinks.map(l => `• Anchor: "${l.anchorText}"\n  Target: ${l.targetTopic}\n  Note: ${l.relevance}`),
        
        `\n5. STRUCTURED DATA RECOMMENDATIONS`,
        ...analysis.structuredDataSuggestions.map(s => `• Type: ${s.type}\n  Reason: ${s.reason}`),
        
        `\n6. OPTIMIZATION CHECKLIST`,
        ...analysis.checklist.map((c, i) => `${checkedItems.has(i) ? '[x]' : '[ ]'} ${c}`),
        
        `\n================================================`,
    ].join('\n');

    navigator.clipboard.writeText(report);
    setIsCopied(true);
    setTimeout(() => setIsCopied(false), 2000);
  };

  const handleExportPDF = () => {
    if (!analysis) return;

    const doc = new jsPDF();
    
    // Styling constants
    const pageWidth = doc.internal.pageSize.getWidth();
    const margin = 20;
    const contentWidth = pageWidth - (margin * 2);
    let yPos = 20;
    
    // Helper to check page bounds
    const checkPageBreak = (heightNeeded: number) => {
      if (yPos + heightNeeded >= 280) {
        doc.addPage();
        yPos = 20;
      }
    };

    // Header
    doc.setFontSize(20);
    doc.setTextColor(15, 23, 42); // slate-900
    doc.text("OrganicIQ Analysis Report", margin, yPos);
    yPos += 10;
    
    doc.setFontSize(12);
    doc.setTextColor(100, 116, 139); // slate-500
    doc.text(`Topic: ${topic || 'Untitled Content'}`, margin, yPos);
    yPos += 20;
    
    // Section: Readability
    checkPageBreak(30);
    doc.setFontSize(14);
    doc.setTextColor(37, 99, 235); // blue-600
    doc.text("Readability Assessment", margin, yPos);
    yPos += 8;
    
    doc.setFontSize(10);
    doc.setTextColor(51, 65, 85); // slate-700
    doc.text(`Score: ${analysis.readability.level}`, margin, yPos);
    yPos += 6;
    
    analysis.readability.suggestions.forEach(s => {
      const lines = doc.splitTextToSize(`• ${s}`, contentWidth);
      checkPageBreak(lines.length * 5);
      doc.text(lines, margin, yPos);
      yPos += (lines.length * 5) + 2;
    });
    yPos += 5;
    
    // Section: Keyword Density
    checkPageBreak(40);
    doc.setFontSize(14);
    doc.setTextColor(37, 99, 235);
    doc.text("Keyword Strategy", margin, yPos);
    yPos += 8;
    
    doc.setFontSize(10);
    doc.setTextColor(51, 65, 85);
    analysis.keywordAnalysis.forEach(k => {
      const text = `${k.keyword}: ${k.count} uses (${k.status})`;
      checkPageBreak(6);
      doc.text(`• ${text}`, margin, yPos);
      yPos += 6;
    });
    yPos += 5;
    
    // Section: Meta Descriptions
    checkPageBreak(40);
    doc.setFontSize(14);
    doc.setTextColor(37, 99, 235);
    doc.text("Meta Description Options", margin, yPos);
    yPos += 8;
    
    doc.setFontSize(10);
    doc.setTextColor(51, 65, 85);
    analysis.metaDescriptions.forEach((d, i) => {
      const lines = doc.splitTextToSize(`${i + 1}. ${d}`, contentWidth);
      checkPageBreak(lines.length * 5);
      doc.text(lines, margin, yPos);
      yPos += (lines.length * 5) + 4;
    });
    yPos += 5;
    
    // Section: Internal Links
    checkPageBreak(40);
    doc.setFontSize(14);
    doc.setTextColor(37, 99, 235);
    doc.text("Internal Linking Opportunities", margin, yPos);
    yPos += 8;
    
    doc.setFontSize(10);
    doc.setTextColor(51, 65, 85);
    analysis.internalLinks.forEach(l => {
      const lines = doc.splitTextToSize(`• Anchor: "${l.anchorText}" -> ${l.targetTopic}`, contentWidth);
      checkPageBreak(lines.length * 5 + 5);
      doc.text(lines, margin, yPos);
      yPos += (lines.length * 5);
      
      doc.setTextColor(100, 116, 139); // lighter
      const relLines = doc.splitTextToSize(`  Note: ${l.relevance}`, contentWidth - 5);
      doc.text(relLines, margin + 5, yPos);
      yPos += (relLines.length * 5) + 4;
      doc.setTextColor(51, 65, 85); // reset
    });
    yPos += 5;
    
    // Section: Structured Data
    checkPageBreak(40);
    doc.setFontSize(14);
    doc.setTextColor(37, 99, 235);
    doc.text("Structured Data Recommendations", margin, yPos);
    yPos += 8;
    
    doc.setFontSize(10);
    doc.setTextColor(51, 65, 85);
    analysis.structuredDataSuggestions.forEach(s => {
       const typeLines = doc.splitTextToSize(`• Type: ${s.type}`, contentWidth);
       checkPageBreak(typeLines.length * 5 + 5);
       doc.text(typeLines, margin, yPos);
       yPos += (typeLines.length * 5);

       doc.setTextColor(100, 116, 139);
       const reasonLines = doc.splitTextToSize(`  Reason: ${s.reason}`, contentWidth - 5);
       doc.text(reasonLines, margin + 5, yPos);
       yPos += (reasonLines.length * 5) + 4;
       doc.setTextColor(51, 65, 85);
    });
    yPos += 5;

    // Section: Checklist
    checkPageBreak(50);
    doc.setFontSize(14);
    doc.setTextColor(37, 99, 235);
    doc.text("Optimization Checklist", margin, yPos);
    yPos += 8;
    
    doc.setFontSize(10);
    doc.setTextColor(51, 65, 85);
    analysis.checklist.forEach((item, i) => {
      const isChecked = checkedItems.has(i);
      const checkbox = isChecked ? "[x]" : "[ ]";
      const lines = doc.splitTextToSize(`${checkbox} ${item}`, contentWidth);
      checkPageBreak(lines.length * 5);
      doc.text(lines, margin, yPos);
      yPos += (lines.length * 5) + 2;
    });
    
    const cleanTopic = (topic || 'report').replace(/[^a-z0-9]/gi, '-').toLowerCase();
    doc.save(`OrganicIQ-${cleanTopic}-${Date.now()}.pdf`);
  };

  return (
    <div className="space-y-6 h-[calc(100vh-140px)] flex flex-col">
      <div className="flex justify-between items-center">
        <h2 className="text-2xl font-bold text-slate-800">Content Generator</h2>
        {content && activeTab === 'preview' && (
            <div className="flex items-center gap-3">
                <span className="text-sm font-medium text-slate-500 bg-white px-3 py-1.5 rounded-lg border border-slate-200 shadow-sm">
                    {wordCount} words
                </span>
                <button 
                  onClick={() => navigator.clipboard.writeText(content)}
                  className="text-slate-500 hover:text-slate-700 flex items-center text-sm bg-white border border-slate-200 px-3 py-1.5 rounded-lg shadow-sm hover:bg-slate-50 transition-colors"
                >
                  <Copy size={14} className="mr-2"/> Copy HTML
                </button>
            </div>
        )}
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6 flex-1 min-h-0">
        {/* Controls */}
        <div className="lg:col-span-1 space-y-4 overflow-y-auto">
          <div className="bg-white p-6 rounded-xl border border-slate-100 shadow-sm space-y-4">
            <div>
              <label className="block text-sm font-medium text-slate-700 mb-2">Article Topic / Keyword</label>
              <input
                type="text"
                value={topic}
                onChange={(e) => setTopic(e.target.value)}
                placeholder="e.g. Top 10 SEO tips for 2024"
                className="w-full p-3 rounded-lg border border-slate-200 bg-slate-50 focus:bg-white focus:border-blue-500 outline-none transition-all"
              />
            </div>
            
            <div>
              <label className="block text-sm font-medium text-slate-700 mb-2">Tone of Voice</label>
              <select 
                value={tone}
                onChange={(e) => setTone(e.target.value)}
                className="w-full p-3 rounded-lg border border-slate-200 focus:border-blue-500 outline-none bg-white"
              >
                <option>Informative</option>
                <option>Persuasive</option>
                <option>Casual</option>
                <option>Professional</option>
                <option>Technical</option>
                <option>Empathetic</option>
                <option>Witty</option>
                <option>Humorous</option>
              </select>
            </div>

            <button
              onClick={handleGenerate}
              disabled={isGenerating || !topic}
              className="w-full bg-blue-600 text-white py-3 rounded-lg font-medium hover:bg-blue-700 disabled:opacity-50 transition-colors flex justify-center items-center"
            >
              {isGenerating ? <Loader2 className="animate-spin mr-2" /> : <PenTool className="mr-2" size={18} />}
              {isGenerating ? 'Writing...' : 'Generate Draft'}
            </button>
          </div>

          <div className="bg-blue-50 p-4 rounded-xl border border-blue-100">
            <h4 className="text-blue-800 font-semibold text-sm mb-2 flex items-center">
              <FileText size={14} className="mr-2"/> Pro Tip
            </h4>
            <p className="text-blue-600 text-xs leading-relaxed">
              Review the generated content for accuracy. Add your own internal links and images to boost SEO performance before publishing.
            </p>
          </div>
        </div>

        {/* Editor / Preview / Analysis */}
        <div className="lg:col-span-2 bg-white rounded-xl border border-slate-100 shadow-sm flex flex-col overflow-hidden h-full">
            {/* Tabs Header */}
            <div className="bg-slate-50 border-b border-slate-200 flex items-center px-2">
                <button
                  onClick={() => setActiveTab('preview')}
                  className={`px-4 py-3 text-sm font-medium flex items-center border-b-2 transition-colors ${
                    activeTab === 'preview' 
                    ? 'border-blue-600 text-blue-600' 
                    : 'border-transparent text-slate-500 hover:text-slate-700'
                  }`}
                >
                  <Eye size={16} className="mr-2" /> Live Preview
                </button>
                <button
                  onClick={() => setActiveTab('seo')}
                  className={`px-4 py-3 text-sm font-medium flex items-center border-b-2 transition-colors ${
                    activeTab === 'seo' 
                    ? 'border-emerald-600 text-emerald-600' 
                    : 'border-transparent text-slate-500 hover:text-slate-700'
                  }`}
                >
                  <Sparkles size={16} className="mr-2" /> SEO Optimizer
                </button>
                
                {isGenerating && <span className="ml-auto mr-4 text-xs text-blue-600 animate-pulse">AI is typing...</span>}
            </div>

            {/* Tab Content */}
            <div className="flex-1 overflow-y-auto p-8">
                {/* Preview Tab */}
                {activeTab === 'preview' && (
                  <div className="prose prose-slate max-w-none prose-headings:font-bold prose-a:text-blue-600">
                      {content ? (
                          <div dangerouslySetInnerHTML={{ __html: content }} />
                      ) : (
                          <div className="h-full flex flex-col items-center justify-center text-slate-300 min-h-[300px]">
                              <RefreshCw size={48} className="mb-4 opacity-50" />
                              <p className="text-sm">Content will appear here</p>
                          </div>
                      )}
                  </div>
                )}

                {/* SEO Tab */}
                {activeTab === 'seo' && (
                  <div className="space-y-6">
                    {!content ? (
                       <div className="text-center text-slate-400 py-12">
                         <p>Generate content first to analyze it for SEO.</p>
                       </div>
                    ) : !analysis ? (
                       <div className="text-center py-12">
                          <p className="text-slate-600 mb-4">Get specific recommendations to rank higher.</p>
                          <button 
                            onClick={handleAnalyze}
                            disabled={isAnalyzing}
                            className="bg-emerald-600 text-white px-6 py-2 rounded-lg hover:bg-emerald-700 disabled:opacity-70 transition-colors inline-flex items-center"
                          >
                             {isAnalyzing ? <Loader2 className="animate-spin mr-2" size={18}/> : <Sparkles className="mr-2" size={18} />}
                             Analyze Content
                          </button>
                       </div>
                    ) : (
                       <div className="animate-fade-in space-y-8">
                          
                          {/* Header with Actions */}
                          <div className="flex justify-between items-center border-b border-slate-100 pb-4">
                            <div>
                              <h3 className="font-bold text-slate-800 text-lg">Analysis Results</h3>
                              <p className="text-sm text-slate-500">AI-generated insights for "{topic}"</p>
                            </div>
                            <div className="flex gap-2">
                                <button 
                                  onClick={handleExportPDF}
                                  className="text-slate-500 hover:text-blue-600 text-sm font-medium flex items-center bg-white border border-slate-200 px-3 py-2 rounded-lg hover:bg-slate-50 transition-colors shadow-sm"
                                >
                                  <Download size={16} className="mr-2"/>
                                  PDF
                                </button>
                                <button 
                                  onClick={handleCopyAnalysis}
                                  className="text-slate-500 hover:text-blue-600 text-sm font-medium flex items-center bg-white border border-slate-200 px-3 py-2 rounded-lg hover:bg-slate-50 transition-colors shadow-sm"
                                >
                                  {isCopied ? <Check size={16} className="mr-2 text-emerald-500"/> : <Copy size={16} className="mr-2"/>}
                                  {isCopied ? 'Copied' : 'Copy'}
                                </button>
                            </div>
                          </div>

                          {/* Meta Descriptions */}
                          <div className="space-y-3">
                             <h3 className="font-bold text-slate-800 flex items-center text-lg">
                                <FileText className="mr-2 text-blue-500" size={20} /> Meta Description Suggestions
                             </h3>
                             <div className="grid gap-3">
                                {analysis.metaDescriptions.map((desc, i) => (
                                   <div key={i} className="bg-slate-50 p-4 rounded-lg border border-slate-200 group relative">
                                      <p className="text-sm text-slate-700 pr-8">{desc}</p>
                                      <button 
                                        onClick={() => navigator.clipboard.writeText(desc)}
                                        className="absolute top-3 right-3 text-slate-400 hover:text-blue-600 opacity-0 group-hover:opacity-100 transition-opacity"
                                        title="Copy"
                                      >
                                         <Copy size={16} />
                                      </button>
                                   </div>
                                ))}
                             </div>
                          </div>

                          <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                             {/* Readability */}
                             <div className="bg-white p-5 rounded-xl border border-slate-100 shadow-sm">
                                <h4 className="font-semibold text-slate-800 mb-3">Readability Score</h4>
                                <div className="flex items-center mb-4">
                                   <div className="text-3xl font-bold text-emerald-600 mr-3">{analysis.readability.level}</div>
                                </div>
                                <ul className="space-y-2">
                                   {analysis.readability.suggestions.map((suggestion, i) => (
                                      <li key={i} className="text-sm text-slate-600 flex items-start">
                                         <AlertTriangle size={14} className="mr-2 text-amber-500 mt-0.5 flex-shrink-0" />
                                         {suggestion}
                                      </li>
                                   ))}
                                </ul>
                             </div>

                             {/* Keyword Density */}
                             <div className="bg-white p-5 rounded-xl border border-slate-100 shadow-sm">
                                <h4 className="font-semibold text-slate-800 mb-3">Keyword Density</h4>
                                <ul className="space-y-3">
                                   {analysis.keywordAnalysis.map((k, i) => (
                                      <li key={i} className="flex items-center justify-between text-sm">
                                         <span className="font-medium text-slate-700">{k.keyword}</span>
                                         <div className="flex items-center">
                                            <span className="text-slate-500 mr-3">{k.count} uses</span>
                                            <span className={`px-2 py-0.5 rounded text-xs font-medium ${
                                               k.status === 'Optimal' ? 'bg-green-100 text-green-700' :
                                               k.status === 'High' ? 'bg-red-100 text-red-700' :
                                               'bg-yellow-100 text-yellow-700'
                                            }`}>
                                               {k.status}
                                            </span>
                                         </div>
                                      </li>
                                   ))}
                                </ul>
                             </div>
                          </div>

                          {/* Internal Linking Opportunities */}
                          <div className="bg-white p-5 rounded-xl border border-slate-100 shadow-sm">
                              <h4 className="font-semibold text-slate-800 mb-3 flex items-center">
                                  <LinkIcon className="mr-2 text-blue-500" size={20} /> Internal Linking Opportunities
                              </h4>
                              <div className="grid gap-3">
                                  {analysis.internalLinks.map((link, i) => (
                                      <div key={i} className="flex items-start p-3 bg-slate-50 rounded-lg border border-slate-200">
                                          <div className="flex-1">
                                              <div className="flex items-center gap-2 mb-1">
                                                  <span className="text-sm font-medium text-slate-700">Anchor:</span>
                                                  <span className="text-sm font-bold text-blue-600 bg-blue-50 px-2 py-0.5 rounded border border-blue-100">"{link.anchorText}"</span>
                                              </div>
                                              <p className="text-xs text-slate-500"><span className="font-medium text-slate-700">Target:</span> {link.targetTopic}</p>
                                          </div>
                                           <div className="text-xs text-slate-500 italic border-l pl-3 ml-3 max-w-xs">
                                              {link.relevance}
                                          </div>
                                      </div>
                                  ))}
                              </div>
                          </div>

                          {/* Structured Data Suggestions */}
                          <div className="bg-white p-5 rounded-xl border border-slate-100 shadow-sm">
                              <h4 className="font-semibold text-slate-800 mb-3 flex items-center">
                                  <Code2 className="mr-2 text-purple-500" size={20} /> Structured Data Recommendations
                              </h4>
                              <div className="grid gap-3 md:grid-cols-2">
                                  {analysis.structuredDataSuggestions.map((data, i) => (
                                      <div key={i} className="p-4 bg-purple-50 rounded-lg border border-purple-100">
                                          <div className="flex items-center mb-2">
                                              <span className="text-sm font-bold text-purple-700">{data.type}</span>
                                              <span className="ml-2 text-[10px] uppercase tracking-wider text-purple-500 bg-white px-1.5 py-0.5 rounded border border-purple-100">JSON-LD</span>
                                          </div>
                                          <p className="text-sm text-slate-600 leading-relaxed">{data.reason}</p>
                                      </div>
                                  ))}
                              </div>
                          </div>

                          {/* Checklist */}
                          <div className="bg-indigo-50 p-6 rounded-xl border border-indigo-100">
                             <div className="flex justify-between items-center mb-4">
                                <h3 className="font-bold text-indigo-900 flex items-center">
                                    <CheckCircle2 className="mr-2" size={20} /> Optimization Checklist
                                </h3>
                                <span className="text-xs font-medium text-indigo-700 bg-indigo-200 px-2 py-1 rounded-full">
                                    {checkedItems.size}/{analysis.checklist.length} Done
                                </span>
                             </div>
                             <ul className="grid grid-cols-1 gap-3">
                                {analysis.checklist.map((item, i) => {
                                   const isChecked = checkedItems.has(i);
                                   return (
                                   <li 
                                      key={i} 
                                      onClick={() => toggleCheck(i)}
                                      className={`flex items-start text-sm p-3 rounded-lg transition-all cursor-pointer select-none border ${
                                          isChecked 
                                            ? 'text-indigo-400 bg-indigo-100/50 border-indigo-100' 
                                            : 'text-indigo-900 bg-white border-indigo-200 hover:border-indigo-300 hover:shadow-sm'
                                      }`}
                                   >
                                      <div className={`
                                          flex-shrink-0 w-5 h-5 rounded border mr-3 mt-0.5 flex items-center justify-center transition-all duration-200
                                          ${isChecked ? 'bg-indigo-500 border-indigo-500' : 'border-indigo-300 bg-slate-50'}
                                      `}>
                                          {isChecked && <Check size={12} className="text-white" strokeWidth={3} />}
                                      </div>
                                      <span className={`transition-all ${isChecked ? 'line-through decoration-indigo-300' : ''}`}>
                                        {item}
                                      </span>
                                   </li>
                                )})}
                             </ul>
                          </div>

                          {/* Bottom Action Buttons */}
                          <div className="flex gap-4 pt-4">
                              <button 
                                  onClick={handleCopyAnalysis}
                                  className="flex-1 bg-white border border-slate-200 text-slate-700 py-3 rounded-xl font-medium hover:bg-slate-50 hover:text-blue-600 transition-colors flex justify-center items-center shadow-sm"
                              >
                                  {isCopied ? <Check size={18} className="mr-2 text-emerald-500"/> : <Copy size={18} className="mr-2"/>}
                                  {isCopied ? 'Copied to Clipboard' : 'Copy Full Analysis'}
                              </button>
                               <button 
                                  onClick={handleExportPDF}
                                  className="flex-1 bg-blue-600 text-white py-3 rounded-xl font-medium hover:bg-blue-700 transition-colors flex justify-center items-center shadow-md shadow-blue-600/20"
                              >
                                  <Download size={18} className="mr-2"/>
                                  Download PDF Report
                              </button>
                          </div>

                       </div>
                    )}
                  </div>
                )}
            </div>
        </div>
      </div>
    </div>
  );
};

export default ContentGenerator;